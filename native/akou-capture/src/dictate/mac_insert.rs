/// `NSPasteboardTypeString`.
pub const TEXT: &str = "public.utf8-plain-text";
pub const CONCEALED: &str = "org.nspasteboard.ConcealedType";
/// What the promise is declared as besides the text.
pub const PROMISE_MARKERS: [&str; 3] = [
    "org.nspasteboard.TransientType",
    CONCEALED,
    "org.nspasteboard.AutoGeneratedType",
];

/// The worker's wait on macOS (`live::serve_with`): a turn of the main run loop, where AppKit
/// serves the pasteboard promise, then the next message. Runs on the main thread only.
pub fn wait(rx: &Receiver<Msg>, step: Duration) -> Result<Msg, RecvTimeoutError> {
    if let Ok(m) = rx.try_recv() {
        return Ok(m);
    }
    // SAFETY: a CF constant.
    let mode = unsafe { kCFRunLoopDefaultMode };
    // With nothing on the run loop yet (no promise was ever made) it returns at once: wait on
    // the queue instead of spinning.
    if CFRunLoop::run_in_mode(mode, step.as_secs_f64(), true) == CFRunLoopRunResult::Finished {
        return rx.recv_timeout(step);
    }
    rx.try_recv().map_err(|e| match e {
        TryRecvError::Empty => RecvTimeoutError::Timeout,
        TryRecvError::Disconnected => RecvTimeoutError::Disconnected,
    })
}

// ---------------------------------------------------------------------------
// The pasteboard

#[derive(Default)]
struct Promise {
    text: String,
    /// When the text was read, on the awake clock the worker uses.
    reads: Vec<u64>,
}

define_class!(
    // SAFETY: NSObject has no subclassing requirements; the ivars are plain Rust values that only
    // the main thread touches, which is where AppKit calls a pasteboard owner.
    #[unsafe(super(NSObject))]
    #[name = "AkouDictatePromise"]
    #[ivars = Rc<RefCell<Promise>>]
    struct PromiseOwner;

    impl PromiseOwner {
        /// An app asked for the promised data: the read receipt when it asked for the text.
        #[unsafe(method(pasteboard:provideDataForType:))]
        fn provide(&self, pasteboard: &AnyObject, ty: &NSString) {
            let payload = {
                let mut p = self.ivars().borrow_mut();
                if ty.to_string() == TEXT {
                    p.reads.push(clock::now().awake_ns);
                    p.text.clone()
                } else {
                    // A marker type carries nothing.
                    String::new()
                }
            };
            let s = NSString::from_str(&payload);
            // SAFETY: `setString:forType:` takes two NSStrings and returns a BOOL.
            let _: bool = unsafe { msg_send![pasteboard, setString: &*s, forType: ty] };
        }
    }
);

impl PromiseOwner {
    fn new(state: Rc<RefCell<Promise>>) -> Retained<Self> {
        let this = Self::alloc().set_ivars(state);
        // SAFETY: NSObject's designated initialiser.
        unsafe { msg_send![super(this), init] }
    }
}

pub struct Pasteboard {
    pb: Retained<AnyObject>,
    state: Rc<RefCell<Promise>>,
    /// The owner of the current promise; the pasteboard does not keep it alive.
    owner: Option<Retained<PromiseOwner>>,
}

fn nsstr(s: &str) -> Retained<NSString> {
    NSString::from_str(s)
}

impl Pasteboard {
    fn with(pb: Retained<AnyObject>) -> Pasteboard {
        Pasteboard {
            pb,
            state: Rc::default(),
            owner: None,
        }
    }

    /// The general pasteboard, the one Command+V reads.
    pub fn general() -> Option<Pasteboard> {
        let cls = AnyClass::get(c"NSPasteboard")?;
        // SAFETY: a class method returning the shared NSPasteboard.
        let pb: Option<Retained<AnyObject>> = unsafe { msg_send![cls, generalPasteboard] };
        pb.map(Pasteboard::with)
    }

    /// A private pasteboard by name (the tests': never the one the user copies to).
    pub fn named(name: &str) -> Option<Pasteboard> {
        let cls = AnyClass::get(c"NSPasteboard")?;
        let n = nsstr(name);
        // SAFETY: a class method taking an NSString and returning an NSPasteboard.
        let pb: Option<Retained<AnyObject>> = unsafe { msg_send![cls, pasteboardWithName: &*n] };
        pb.map(Pasteboard::with)
    }

    /// Frees a named pasteboard.
    pub fn release_globally(&self) {
        // SAFETY: no arguments, no result.
        let _: () = unsafe { msg_send![&*self.pb, releaseGlobally] };
    }

    fn clear(&mut self) {
        self.owner = None;
        // SAFETY: returns the new change count, unused here.
        let _: isize = unsafe { msg_send![&*self.pb, clearContents] };
    }
}

impl Clipboard for Pasteboard {
    fn snapshot(&mut self) -> Snapshot {
        autoreleasepool(|_| {
            let mut out = Vec::new();
            // SAFETY: `pasteboardItems` returns an NSArray of NSPasteboardItem, or nil.
            let items: Option<Retained<NSArray<AnyObject>>> =
                unsafe { msg_send![&*self.pb, pasteboardItems] };
            for (i, item) in items.iter().flat_map(|a| a.iter()).enumerate() {
                // SAFETY: `types` returns an NSArray of NSString.
                let types: Option<Retained<NSArray<NSString>>> =
                    unsafe { msg_send![&*item, types] };
                for ty in types.iter().flat_map(|a| a.iter()) {
                    // SAFETY: `dataForType:` takes an NSString and returns NSData or nil.
                    let data: Option<Retained<NSData>> =
                        unsafe { msg_send![&*item, dataForType: &*ty] };
                    if let Some(d) = data {
                        out.push((format!("{i}\t{ty}"), d.to_vec()));
                    }
                }
            }
            out
        })
    }

    fn publish(&mut self, text: &str) -> Result<u64, String> {
        autoreleasepool(|_| {
            // A fresh record per promise: a late read of an older one lands nowhere.
            self.state = Rc::new(RefCell::new(Promise {
                text: text.to_string(),
                reads: Vec::new(),
            }));
            let owner = PromiseOwner::new(self.state.clone());
            let types: Vec<Retained<NSString>> = std::iter::once(TEXT)
                .chain(PROMISE_MARKERS)
                .map(nsstr)
                .collect();
            let types = NSArray::from_retained_slice(&types);
            // SAFETY: `declareTypes:owner:` takes an NSArray of NSString and any object, and
            // returns the new change count.
            let count: isize =
                unsafe { msg_send![&*self.pb, declareTypes: &*types, owner: &*owner] };
            self.owner = Some(owner);
            if count <= 0 {
                return Err("clipboard-publish".into());
            }
            Ok(count as u64)
        })
    }

    fn write(&mut self, text: &str, concealed: bool) -> Result<(), String> {
        autoreleasepool(|_| {
            self.clear();
            let (s, ty) = (nsstr(text), nsstr(TEXT));
            // SAFETY: `setString:forType:` takes two NSStrings and returns a BOOL.
            let ok: bool = unsafe { msg_send![&*self.pb, setString: &*s, forType: &*ty] };
            if ok && concealed {
                let (empty, marker) = (NSData::with_bytes(&[]), nsstr(CONCEALED));
                // SAFETY: `setData:forType:` takes NSData and an NSString and returns a BOOL.
                let _: bool = unsafe { msg_send![&*self.pb, setData: &*empty, forType: &*marker] };
            }
            if ok {
                Ok(())
            } else {
                Err("clipboard-write".into())
            }
        })
    }

    fn change_count(&mut self) -> u64 {
        // SAFETY: returns an NSInteger.
        let c: isize = unsafe { msg_send![&*self.pb, changeCount] };
        c.max(0) as u64
    }

    fn restore(&mut self, snapshot: &Snapshot) {
        autoreleasepool(|_| {
            self.clear();
            let Some(cls) = AnyClass::get(c"NSPasteboardItem") else {
                return;
            };
            let mut items: Vec<Retained<AnyObject>> = Vec::new();
            let mut index = None;
            for (key, bytes) in snapshot {
                let Some((i, ty)) = key.split_once('\t') else {
                    continue;
                };
                if index != Some(i) {
                    // SAFETY: `new` returns a +1 NSPasteboardItem.
                    items.push(unsafe { msg_send![cls, new] });
                    index = Some(i);
                }
                let Some(item) = items.last() else { continue };
                let (d, t) = (NSData::with_bytes(bytes), nsstr(ty));
                // SAFETY: `setData:forType:` takes NSData and an NSString and returns a BOOL.
                let _: bool = unsafe { msg_send![&**item, setData: &*d, forType: &*t] };
            }
            if !items.is_empty() {
                let items = NSArray::from_retained_slice(&items);
                // SAFETY: `writeObjects:` takes an NSArray of pasteboard writers.
                let _: bool = unsafe { msg_send![&*self.pb, writeObjects: &*items] };
            }
        });
    }

    fn reads(&mut self) -> Vec<u64> {
        std::mem::take(&mut self.state.borrow_mut().reads)
    }
}

