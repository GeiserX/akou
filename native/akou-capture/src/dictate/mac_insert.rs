// The events

pub struct Events {
    source: CFRetained<CGEventSource>,
}

impl Events {
    pub fn new() -> Option<Events> {
        let source = CGEventSource::new(CGEventSourceStateID::Private)?;
        CGEventSource::set_user_data(Some(&source), AKOU_EVENT);
        Some(Events { source })
    }

    fn event(
        &self,
        code: u16,
        down: bool,
        flags: u64,
        modifier: bool,
    ) -> Result<CFRetained<CGEvent>, String> {
        let e =
            CGEvent::new_keyboard_event(Some(&self.source), code, down).ok_or("no-key-event")?;
        if modifier {
            CGEvent::set_type(Some(&e), CGEventType::FlagsChanged);
        }
        CGEvent::set_flags(Some(&e), CGEventFlags(flags));
        CGEvent::set_integer_value_field(Some(&e), CGEventField::EventSourceUserData, AKOU_EVENT);
        Ok(e)
    }

    /// `mods` then `code`: each modifier down, the key down and up with the modifiers' flags,
    /// the modifiers up in reverse.
    pub fn chord(&self, mods: &[&str], code: u16) -> Result<Vec<CFRetained<CGEvent>>, String> {
        let keys = mods
            .iter()
            .map(|m| mac_keys::modifier_key(m).ok_or_else(|| format!("no-modifier {m}")))
            .collect::<Result<Vec<_>, _>>()?;
        let mut out = Vec::new();
        let mut flags = 0;
        for (c, f) in &keys {
            flags |= f;
            out.push(self.event(*c, true, flags, true)?);
        }
        out.push(self.event(code, true, flags, false)?);
        out.push(self.event(code, false, flags, false)?);
        for (c, f) in keys.iter().rev() {
            flags &= !f;
            out.push(self.event(*c, false, flags, true)?);
        }
        Ok(out)
    }

    /// One piece of the typed path as a key-down and a key-up carrying it.
    pub fn text(&self, text: &str) -> Result<Vec<CFRetained<CGEvent>>, String> {
        let units: Vec<u16> = text.encode_utf16().collect();
        if units.len() > TYPE_CHUNK || text.contains(['\n', '\r']) {
            return Err("type-piece".into());
        }
        [true, false]
            .into_iter()
            .map(|down| {
                let e = self.event(0, down, 0, false)?;
                // SAFETY: `units` holds `units.len()` UTF-16 units and outlives the call.
                unsafe {
                    CGEvent::keyboard_set_unicode_string(Some(&e), units.len() as _, units.as_ptr())
                };
                Ok(e)
            })
            .collect()
    }

    fn post(&self, events: Vec<CFRetained<CGEvent>>) -> Result<(), String> {
        if !trusted() {
            return Err("no-grant".into());
        }
        for e in events {
            CGEvent::post(CGEventTapLocation::HIDEventTap, Some(&e));
        }
        Ok(())
    }
}

fn flags_now() -> u64 {
    CGEventSource::flags_state(CGEventSourceStateID::CombinedSessionState).0
}

impl Sink for Events {
    fn held_modifiers(&mut self) -> Vec<String> {
        mac_keys::held_modifiers(flags_now())
    }

    fn modifier(&mut self, name: &str, down: bool) -> Result<(), String> {
        let (code, f) =
            mac_keys::modifier_key(name).ok_or_else(|| format!("no-modifier {name}"))?;
        let flags = if down {
            flags_now() | f
        } else {
            flags_now() & !f
        };
        let e = self.event(code, down, flags, true)?;
        self.post(vec![e])
    }

    fn press(&mut self, mods: &[&str], key: Key) -> Result<(), String> {
        let code = match key {
            Key::Code(c) => c,
            Key::Named(n) => mac_keys::key_code(n).ok_or_else(|| format!("no-key {n}"))?,
        };
        let events = self.chord(mods, code)?;
        self.post(events)
    }

    fn keycode(&mut self, ch: char) -> Option<u16> {
        layout::keycode(ch)
    }

    fn type_text(&mut self, text: &str) -> Result<(), String> {
        let events = self.text(text)?;
        self.post(events)
    }
}

