//! The macOS inserter of `akou-capture dictate` (docs/ux/DICTATION.md DC-N6, DC-N7, DC-N8): the
//! general pasteboard behind `insert::Clipboard` and the key events behind `insert::Sink`. The
//! receipt rules themselves are in `insert`, the same on every OS.
//!
//! - **The promise.** A paste publishes the text with `declareTypes:owner:`, so the pasteboard
//!   holds a promise, not the text; when an app reads it, AppKit asks the owner
//!   (`pasteboard:provideDataForType:`), and that call is the read receipt. Only a read of the
//!   text counts: a read of a marker type is a clipboard manager looking at the markers. The
//!   promise is marked transient, concealed and generated (nspasteboard.org), so a well-behaved
//!   clipboard manager neither keeps nor shows it.
//! - **The main run loop.** AppKit serves a promise only on the main thread's run loop, whichever
//!   thread declared it (measured in docs/gates/dc-n6-mac-paste-promise.md). The worker loop runs
//!   on the main thread, and `wait` turns the main run loop while it waits for its next message,
//!   so a read is answered within one step. The keyboard layout calls (`TIS*`) need the main
//!   thread as well.
//! - **The snapshot** is every type of every item, read before the promise replaces them; the
//!   restore writes the same items back. A snapshot key is `index<TAB>type`.
//! - **The events** come from a private event source (`kCGEventSourceStatePrivate`), so the
//!   user's own held keys do not leak into them, and each carries `mac::AKOU_EVENT` so the
//!   helper's own tap lets it pass. A chord is its modifiers down, the key down and up with the
//!   modifiers' flags, then the modifiers up, posted at the HID level. The V of the paste chord is
//!   looked up on the active layout with Command held (`UCKeyTranslate`), so Dvorak gets its own
//!   V and "Dvorak - QWERTY Command" gets the QWERTY one; a layout that types no V at all (Russian,
//!   Greek) falls back to the ASCII-capable layout macOS itself uses for shortcuts. There is no
//!   assumed key code.
//! - **The typed path** is one key-down and key-up per piece, each with the piece as its Unicode
//!   string (`CGEventKeyboardSetUnicodeString`, at most `TYPE_CHUNK` UTF-16 units).
//! - **No grant, no events.** Without the Accessibility grant macOS drops posted events without a
//!   word, so a press answers `no-grant` at once and the paste settles as a failed chord.
//!
//! The tests here build events and never post them; the pasteboard and the layouts are exercised
//! on a private named pasteboard by `tests/mac_pasteboard.rs`, and a real paste into a real text
//! view runs only on the CI macOS runner (`.github/workflows/ci.yml`).

